#!/usr/bin/env python3
"""Kick Flight country geo-block (JP/CN/KR) as an nftables table `inet kf_geoblock`.

Subcommands: refresh | generate | disable | status | install
See docs/GEO_BLOCK.md. Fail-safe: a failed or implausibly small download never
replaces the active ruleset; the last good CIDR cache is reused instead.
"""
import argparse, ipaddress, os, shutil, subprocess, sys, tempfile, urllib.request
from pathlib import Path

COUNTRIES = ("jp", "cn", "kr")
V4_URL = "https://www.ipdeny.com/ipblocks/data/aggregated/{cc}-aggregated.zone"
V6_URL = "https://www.ipdeny.com/ipv6/ipaddresses/aggregated/{cc}-aggregated.zone"
# Sanity floors (real lists are far larger); below this the download is rejected.
MIN_V4, MIN_V6 = 200, 20
# Public service ports (SSH 22 is deliberately NOT listed -> never geo-blocked).
PORTS = "80, 443, 18080, 18081, 5055, 5056, 5058, 27000-27002"
TABLE = "kf_geoblock"
CACHE = Path(os.environ.get("KF_GEOBLOCK_CACHE", "/var/lib/kickflight-geoblock"))
DISABLE_FLAG = Path(os.environ.get("KF_GEOBLOCK_DISABLE_FLAG", "/etc/kickflight/geoblock.disabled"))
SBIN = Path("/usr/local/sbin/kf-geoblock")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "kickflight-geoblock/1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("ascii")


def parse(text, version):
    nets = []
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            n = ipaddress.ip_network(line, strict=False)
            if n.version != version:
                raise ValueError("wrong IP version: " + line)
            nets.append(n)
    return nets


def load_lists(cache_dir, offline=False):
    """Return {(cc, ver): [networks]}; download, validate, update cache, else fall back to cache."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    out, warn = {}, []
    for cc in COUNTRIES:
        for ver, tpl, floor in ((4, V4_URL, MIN_V4), (6, V6_URL, MIN_V6)):
            f = cache_dir / f"{cc}.v{ver}.zone"
            nets = None
            if not offline:
                try:
                    text = fetch(tpl.format(cc=cc))
                    nets = parse(text, ver)
                    if len(nets) < floor:
                        raise ValueError(f"only {len(nets)} entries (< {floor})")
                    tmp = f.with_suffix(".tmp")
                    tmp.write_text(text)
                    tmp.replace(f)
                except Exception as e:  # keep previous cache
                    warn.append(f"{cc} v{ver}: download rejected ({e}); using cache")
                    nets = None
            if nets is None:
                if not f.exists():
                    raise SystemExit(f"no usable data for {cc} v{ver} and no cache; ruleset untouched")
                nets = parse(f.read_text(), ver)
                if len(nets) < floor:
                    raise SystemExit(f"cache for {cc} v{ver} implausibly small; ruleset untouched")
            out[(cc, ver)] = nets
    return out, warn


def render(lists):
    def elems(ver):
        allnets = [n for (cc, v), ns in lists.items() if v == ver for n in ns]
        merged = ipaddress.collapse_addresses(allnets)
        return ",\n      ".join(str(n) for n in merged)
    pl = f"{{ {PORTS} }}"
    return f"""# generated by kf-geoblock.py (countries: {', '.join(c.upper() for c in COUNTRIES)})
add table inet {TABLE}
delete table inet {TABLE}
table inet {TABLE} {{
  set geo4 {{
    type ipv4_addr; flags interval
    elements = {{
      {elems(4)}
    }}
  }}
  set geo6 {{
    type ipv6_addr; flags interval
    elements = {{
      {elems(6)}
    }}
  }}
  chain input {{
    type filter hook input priority -150; policy accept;
    iifname "lo" accept
    meta l4proto {{ tcp, udp }} th dport {pl} ip saddr @geo4 counter drop
    meta l4proto {{ tcp, udp }} th dport {pl} ip6 saddr @geo6 counter drop
  }}
  # Docker-published ports are DNATed and traverse FORWARD, not INPUT.
  chain forward {{
    type filter hook forward priority -150; policy accept;
    ct status dnat meta l4proto {{ tcp, udp }} ct original proto-dst {pl} ip saddr @geo4 counter drop
    ct status dnat meta l4proto {{ tcp, udp }} ct original proto-dst {pl} ip6 saddr @geo6 counter drop
  }}
}}
"""


def nft(args, check=True):
    return subprocess.run(["nft", *args], check=check, capture_output=True, text=True)


def cmd_generate(a):
    lists, warn = load_lists(Path(a.cache), offline=a.offline)
    for w in warn:
        print("WARN:", w, file=sys.stderr)
    for (cc, v), ns in lists.items():
        print(f"{cc.upper()} v{v}: {len(ns)} CIDRs", file=sys.stderr)
    text = render(lists)
    Path(a.output).write_text(text)
    print(f"wrote {a.output}", file=sys.stderr)
    if a.check and shutil.which("nft"):
        r = nft(["-c", "-f", a.output], check=False)
        print("nft -c:", "OK" if r.returncode == 0 else "FAILED\n" + r.stderr, file=sys.stderr)
        return r.returncode
    return 0


def cmd_refresh(a):
    if DISABLE_FLAG.exists():
        print(f"{DISABLE_FLAG} present: geo-block disabled, removing table")
        nft(["delete", "table", "inet", TABLE], check=False)
        return 0
    lists, warn = load_lists(CACHE)
    for w in warn:
        print("WARN:", w, file=sys.stderr)
    with tempfile.NamedTemporaryFile("w", suffix=".nft", delete=False) as t:
        t.write(render(lists))
    try:
        r = nft(["-c", "-f", t.name], check=False)  # validate first; on error keep old rules
        if r.returncode:
            raise SystemExit("generated ruleset invalid, active rules untouched:\n" + r.stderr)
        r = nft(["-f", t.name], check=False)  # atomic: add+delete+recreate in one transaction
        if r.returncode:
            raise SystemExit("nft load failed:\n" + r.stderr)
    finally:
        os.unlink(t.name)
    print("geo-block loaded:", ", ".join(f"{c.upper()}v{v}={len(n)}" for (c, v), n in lists.items()))
    return 0


def cmd_disable(a):
    nft(["delete", "table", "inet", TABLE], check=False)
    DISABLE_FLAG.parent.mkdir(parents=True, exist_ok=True)
    DISABLE_FLAG.touch()
    print("geo-block removed; flag set (refresh will keep it off). `rm` the flag to re-enable.")
    return 0


def cmd_status(a):
    r = nft(["list", "table", "inet", TABLE], check=False)
    print("ACTIVE" if r.returncode == 0 else "NOT LOADED", "| disabled flag:", DISABLE_FLAG.exists())
    if r.returncode == 0:
        for l in r.stdout.splitlines():
            if "counter" in l:
                print(l.strip())
    return 0


def cmd_install(a):
    """Install script + systemd units, then refresh. Run as root."""
    here = Path(__file__).resolve().parent.parent
    shutil.copy2(__file__, SBIN)
    SBIN.chmod(0o755)
    for u in ("kickflight-geoblock.service", "kickflight-geoblock.timer"):
        shutil.copy2(here / "deploy/geoblock" / u, "/etc/systemd/system/" + u)
    subprocess.run(["systemctl", "daemon-reload"], check=True)
    subprocess.run(["systemctl", "enable", "kickflight-geoblock.timer"], check=True)
    subprocess.run(["systemctl", "start", "kickflight-geoblock.timer"], check=True)
    return cmd_refresh(a)


def main():
    p = argparse.ArgumentParser()
    sp = p.add_subparsers(dest="cmd", required=True)
    for n in ("refresh", "disable", "status", "install"):
        sp.add_parser(n)
    g = sp.add_parser("generate")
    g.add_argument("--output", required=True)
    g.add_argument("--cache", required=True)
    g.add_argument("--offline", action="store_true")
    g.add_argument("--check", action="store_true")
    a = p.parse_args()
    sys.exit({"refresh": cmd_refresh, "generate": cmd_generate, "disable": cmd_disable,
              "status": cmd_status, "install": cmd_install}[a.cmd](a))


if __name__ == "__main__":
    main()
